import { REAL_TIMERS } from './real-timers';

/**
 * Колбэк, который выполнится, когда текущая очередь микрозадач опустеет, —
 * раньше любой макрозадачи (таймера, ввода-вывода, `setImmediate`). Обещание,
 * разрешённое до него, разрешилось «сразу»: без единого обращения к циклу
 * событий.
 *
 * Два `nextTick` с микрозадачей между ними: `nextTick`, поставленный из
 * микрозадачи, выполняется после опустошения очереди микрозадач, а
 * поставленный из синхронной части макрозадачи — ДО неё; вторая ступень
 * закрывает этот случай.
 */
export const afterMicrotaskDrain = (callback: () => void): void => {
  // Настоящий nextTick и микрозадача обещания: фальшивые таймеры jest подменяют и nextTick, и queueMicrotask.
  REAL_TIMERS.nextTick(() => {
    void Promise.resolve().then(() => REAL_TIMERS.nextTick(callback));
  });
};
