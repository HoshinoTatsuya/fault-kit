/**
 * Граница окна без стенных часов: явное событие (обещание, которое разрешится,
 * когда граница наступила) или число оборотов цикла событий (макрозадач
 * `setImmediate`). Обороты годятся только для работы БЕЗ ввода-вывода: сколько
 * оборотов займёт ответ сети, зависит от скорости машины. Для сети граница —
 * событие-свидетель: «за это время сервер ответил напрямую двадцать раз».
 */
export type Deadline = PromiseLike<unknown> | { readonly turns: number };
