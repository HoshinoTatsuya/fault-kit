/**
 * Тело `sh -c`: запустить команду и ПОСЛЕ неё выйти с её кодом. Команда не
 * последняя, поэтому оболочка не заменяет себя ею (`exec`-оптимизацию
 * последней команды делают и bash, и dash) — между запускающим и командой
 * остаётся отдельный процесс, как у скрипта-обёртки, `npm run` или `sh -c`
 * в конфиге CI. Сигнал, посланный только оболочке, команду не задевает.
 */
export const SHELL_WRAPPER_SCRIPT = '"$0" "$@"; status=$?; exit "$status"';
