import type { Readable } from 'node:stream';

import { LineReader } from './line-reader';

/**
 * Первая непрочитанная строка потока, подходящая под образец (подстрока или
 * регулярное выражение), — событие «процесс дошёл до этого места» вместо
 * паузы на время. Все вызовы для одного потока идут через ОДИН читатель с
 * буфером (`LineReader.of`): последовательные ожидания видят строки,
 * пришедшие между ними или тем же куском. Строки, пришедшие ДО первого
 * вызова для потока, не видны — подписываться до того, как строка может
 * появиться. Поток закончился раньше — отказ с последними строками.
 */
export const waitForLine = (stream: Readable, match: string | RegExp): Promise<string> =>
  LineReader.of(stream).waitFor(match);
