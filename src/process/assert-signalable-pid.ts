/**
 * pid, по которому можно слать сигнал: целое, по модулю больше 1 (отрицательное —
 * группа процессов). Остальное — отказ ДО `process.kill`, а не «нет процесса»:
 * для `kill()` эти значения не означают «никого».
 *
 * - `-1` — ВСЕ процессы, которым вызывающий вправе слать сигнал. 16.11.2026
 *   сентинел `child.pid ?? -1` под мутантом `??`→`&&` закрыл все приложения
 *   пользователя (`process.kill(-1, 'SIGTERM')`), включая VPN и Docker;
 * - `0` — своя группа процессов (то есть сам тест и его раннер);
 * - `1` / `-1` как группа — init/launchd;
 * - не целое число: `process.kill(NaN)` бросает, но позже и с чужим текстом.
 *
 * Проверка стоит прямо перед вызовом: защита, которая проверяет ИСТОЧНИК pid,
 * а не значение, обходится следующим источником.
 */
export const assertSignalablePid = (pid: number): void => {
  if (!Number.isSafeInteger(pid) || Math.abs(pid) <= 1) {
    throw new RangeError(`pid ${String(pid)} не адресует один процесс или группу: сигнал не послан`);
  }
};
